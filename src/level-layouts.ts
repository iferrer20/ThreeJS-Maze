export const checkpointTile = 11;
const startTile = 4;
const finishTile = 3;
const tiles = new Map(Object.entries({
  '__': 0, '##': 1, '~~': 2, FF: finishTile, SS: startTile, CC: checkpointTile,
}));

export const tileSubdivisions = 4;
export const subtileSize = 1 / tileSubdivisions;
export const subtileToBoard = (index: number) => (index + 0.5) * subtileSize - 0.5;

type Coverage = (x: number, z: number) => boolean;
const shapes: [shape: string, covers: Coverage][] = [
  [']', x => x < 2],
  ['[', x => x >= 2],
  ['v', (_, z) => z < 2],
  ['^', (_, z) => z >= 2],
  ['|', x => x === 1 || x === 2],
  ['-', (_, z) => z === 1 || z === 2],
];
const partialTiles = new Map<number, { fill: number; covers: Coverage }>();
for (const [index, [shape, covers]] of shapes.entries()) {
  const floor = 12 + index * 2;
  const wall = floor + 1;
  tiles.set(`_${shape}`, floor);
  tiles.set(`#${shape}`, wall);
  partialTiles.set(floor, { fill: 0, covers });
  partialTiles.set(wall, { fill: 1, covers });
}

// Rendering and physics share this finer grid so their edges line up.
export function expandFloorTiles(map: number[][]) {
  return map.flatMap(row => Array.from({ length: tileSubdivisions }, (_, z) =>
    row.flatMap(tile => {
      const partial = partialTiles.get(tile);
      return Array.from({ length: tileSubdivisions }, (_, x) =>
        partial ? (partial.covers(x, z) ? partial.fill : 2) : tile);
    })));
}

export const levelMaps = layouts.map((layout, index) => {
  const rows = layout.trim().split(/\r?\n/).map(row => row.trim().split(/\s+/));
  const width = rows[0].length;
  if (!width || rows.some(row => row.length !== width)) {
    throw new Error(`Level ${index + 1} must have rows of equal width.`);
  }

  let starts = 0;
  let finishes = 0;
  const map = rows.map(row => Array.from(row, symbol => {
    const tile = tiles.get(symbol);
    if (tile === undefined) throw new Error(`Unknown tile "${symbol}" in level ${index + 1}.`);
    if (tile === startTile) starts++;
    if (tile === finishTile) finishes++;
    return tile;
  }));
  if (starts !== 1 || finishes === 0) {
    throw new Error(`Level ${index + 1} needs one start (SS) and at least one finish (FF).`);
  }
  return map;
});
